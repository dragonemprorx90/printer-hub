import 'dart:convert';
import 'dart:io';

import 'package:flutter_test/flutter_test.dart';
import 'package:printer_hub/gcode.dart';
import 'package:printer_hub/console_page.dart';
import 'package:printer_hub/history_page.dart';
import 'package:printer_hub/moonraker.dart';
import 'package:printer_hub/notify.dart';
import 'package:printer_hub/settings.dart';
import 'package:shared_preferences/shared_preferences.dart';

void main() {
  setUp(() async {
    SharedPreferences.setMockInitialValues({});
    await settings.load();
  });

  test('a multi-spool job is priced at its spools\' average', () {
    expect(spoolPrice([Spool(1, 'a', 'PLA', null, 900, 20), Spool(2, 'b', 'PLA', null, 900, 30)]), 25);
    expect(spoolPrice([Spool(1, 'a', 'PLA', null, 900)]), isNull);
    expect(historyCsv([]).trim(), contains('filament_g'));
  });

  test('settings backups leave out model-site sign-ins', () {
    settings
      ..setText('models.creality.token', 'secret')
      ..setText('models.thingiverse', 'secret')
      ..setText('theme', 'light');
    final backup = settings.exportAll();
    expect(backup['theme'], 'light');
    expect(backup.keys.where(AppSettings.secretKeys.contains), isEmpty);
  });

  test('lruPut keeps the newest entries and refreshes reused ones', () {
    final m = <int, String>{};
    for (var i = 0; i < 5; i++) {
      lruPut(m, i, () => '$i', cap: 3);
    }
    expect(m.keys, [2, 3, 4]);
    lruPut(m, 2, () => 'new', cap: 3);
    expect([m.keys.toList(), m[2]], [[3, 4, 2], '2']);
  });

  test('thumbnail and K2 file details are cached', () async {
    var reads = 0;
    final server = await HttpServer.bind(InternetAddress.loopbackIPv4, 0);
    server.listen((req) {
      if (req.uri.path == '/server/files/metadata') {
        req.response.write(jsonEncode({'result': {'slicer': 'Unknown', 'modified': 1, 'size': 99}}));
      } else {
        reads++;
        req.response.write('; generated by Creality_Print V7.3.0.1\n; estimated printing time (normal mode) = 1h\n');
      }
      req.response.close();
    });
    final c = MoonrakerClient(host: '127.0.0.1', port: server.port);
    expect((await c.metadata('a.gcode'))['estimated_time'], 3600);
    expect((await c.metadata('a.gcode'))['slicer'], 'Creality Print');
    expect(reads, 2, reason: 'head + tail once, then from the cache');

    for (var i = 0; i < 305; i++) {
      Thumbs.of(c, 'f$i.gcode').ignore();
    }
    expect(Thumbs.cached, 300);
    await server.close(force: true);
  });

  test('console history walks back and forward like a shell', () {
    final h = CommandHistory(['G28']);
    h.add('M105');
    h.add('G28'); // a repeat moves to the end
    expect(h.items, ['M105', 'G28']);
    expect([h.back(), h.back(), h.back()], ['G28', 'M105', 'M105']);
    expect([h.forward(), h.forward()], ['G28', '']);
    for (var i = 0; i < 40; i++) {
      h.add('C$i');
    }
    expect(h.items.length, 30);
    expect(CommandHistory([]).back(), isNull);
  });

  test('first-layer and almost-done alerts fire once each, only while printing', () {
    expect(milestones(state: 'printing', layer: 1, eta: 3000, sent: {}), isEmpty);
    expect(milestones(state: 'printing', layer: 2, eta: 3000, sent: {}), {'first'});
    expect(milestones(state: 'printing', layer: 40, eta: 500, sent: {'first'}), {'almost'});
    expect(milestones(state: 'printing', layer: 41, eta: 400, sent: {'first', 'almost'}), isEmpty);
    expect(milestones(state: 'paused', layer: 2, eta: 100, sent: {}), isEmpty);
  });
}
